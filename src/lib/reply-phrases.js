const fill = (tpl, vars = {}) =>
  String(tpl).replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined || vars[k] === null ? '' : String(vars[k])));

/** Base language code: 'ta-IN' -> 'ta', 'od' (Sarvam's Odia) -> 'or'. */
export function replyLang(lang) {
  const base = String(lang || 'en').trim().toLowerCase().split(/[-_]/)[0];
  return base === 'od' ? 'or' : (base || 'en');
}

/** The phrase in that language, or null when there is none (caller falls back). */
export function say(key, lang, vars = {}) {
  const tpl = P[replyLang(lang)]?.[key];
  return tpl ? fill(tpl, vars) : null;
}

/** True for languages that have their own time words here. */
export function hasTimeWords(lang) {
  return !!TIME_WORDS[replyLang(lang)];
}

/**
 * Day + time words for the 8 languages added in T27.
 * diff = calendar days from today; hour 0-23. Returns null for other languages.
 */
export function naturalTimeWords(lang, diff, hour, minute, fallbackDate = '') {
  const w = TIME_WORDS[replyLang(lang)];
  if (!w) return null;
  const dateStr = diff === 0 ? w[0] : diff === 1 ? w[1] : diff === 2 ? w[2] : fallbackDate;
  const period = hour < 12 ? w[3] : hour < 16 ? w[4] : hour < 20 ? w[5] : w[6];
  const h = hour % 12 === 0 ? 12 : hour % 12;
  const timeStr = minute === 0
    ? fill(w[7], { p: period, h })
    : fill(w[8], { p: period, h, m: minute < 10 ? `0${minute}` : minute });
  return { dateStr, timeStr, full: `${dateStr ? dateStr + ' ' : ''}${timeStr}`.trim() };
}

/** "A, B or C" in that language. */
export function joinOr(names, lang) {
  const list = (names || []).filter(Boolean);
  if (list.length < 2) return list[0] || '';
  const orWord = P[replyLang(lang)]?.or || 'or';
  return `${list.slice(0, -1).join(', ')} ${orWord} ${list[list.length - 1]}`;
}
